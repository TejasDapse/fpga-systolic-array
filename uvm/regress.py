#!/usr/bin/env python3
"""UVM regression (Phase 6, Day 44): directed tests + constrained-random seeds.

Configurations (N, K_MAX): (4, 64), (8, 64), (16, 64), (8, 128).

Builds the testbench per N (make build), runs every (test, seed) in parallel,
marks a run PASSED only if it printed "TEST PASSED" with no UVM_ERROR/FATAL and
no assertion failure, merges the functional-coverage bin files and writes
docs/results/uvm_regression.md.

    python3 uvm/regress.py                    # full regression
    python3 uvm/regress.py --seeds 3 --config 4:64   # quicker
"""
import argparse
import os
import re
import subprocess
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

UVM = Path(__file__).resolve().parent
ROOT = UVM.parent
SOLVER = Path(os.environ.get("FPGA_ENV", Path.home() / "miniconda3" / "envs" / "fpga")) / "bin"

DIRECTED = ["mm_reg_access_test", "mm_edge_values_test", "mm_back_to_back_test",
            "mm_start_while_busy_test", "mm_soft_reset_test", "mm_hard_reset_test"]
RANDOM = [("mm_random_test", 200), ("mm_all_test", 50)]


CONFIGS = ["4:64", "8:64", "16:64", "8:128"]


def build(cfg):
    n, k = cfg.split(":")
    print(f"building N={n} K_MAX={k} ...", flush=True)
    r = subprocess.run(["make", "-s", "build", f"N={n}", f"KMAX={k}"], cwd=UVM,
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"build {cfg} failed:\n{r.stdout[-3000:]}{r.stderr[-3000:]}")


def run_one(cfg, test, seed, jobs):
    n, k = cfg.split(":")
    build_dir = UVM / "build" / f"n{n}_k{k}"
    cov = build_dir / f"cov_{test}_{seed}.txt"
    log = build_dir / f"log_{test}_{seed}.txt"
    cmd = [str(build_dir / "Vtb_top"), f"+TEST={test}", f"+JOBS={jobs}",
           f"+verilator+seed+{seed}", f"+COVFILE={cov}"]
    env = dict(os.environ, PATH=f"{SOLVER}:{os.environ['PATH']}")
    r = subprocess.run(cmd, cwd=UVM, capture_output=True, text=True, env=env, timeout=3600)
    out = r.stdout + r.stderr
    log.write_text(out)
    errors = sum(int(x) for x in re.findall(r"^UVM_(?:ERROR|FATAL) :\s+(\d+)", out, re.M))
    asserts = len(re.findall(r"Assertion failed", out))
    m = re.search(r"\[SB\] (\d+) checks, (\d+) jobs", out)
    checks, njobs = (int(m.group(1)), int(m.group(2))) if m else (0, 0)
    passed = r.returncode == 0 and "TEST PASSED" in out and errors == 0 and asserts == 0
    return {"n": cfg, "test": test, "seed": seed, "passed": passed, "errors": errors,
            "asserts": asserts, "checks": checks, "jobs": njobs, "cov": cov if cov.exists() else None,
            "log": log}


def merge_coverage(results):
    hits = defaultdict(int)
    for r in results:
        if r["cov"]:
            for line in r["cov"].read_text().splitlines():
                key, count = line.rsplit(" ", 1)
                hits[key] += int(count)
    groups = defaultdict(lambda: [0, 0])
    for key, count in hits.items():
        g = key.split(".", 1)[0]
        groups[g][1] += 1
        groups[g][0] += count > 0
    return hits, groups


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--config", nargs="*", default=CONFIGS, help="N:K_MAX pairs")
    ap.add_argument("--seeds", type=int, default=10, help="seeds per random test")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "results" / "uvm_regression.md")
    args = ap.parse_args()

    for cfg in args.config:
        build(cfg)
    runs = [(c, t, 1, 0) for c in args.config for t in DIRECTED]
    runs += [(c, t, s, j) for c in args.config for t, j in RANDOM for s in range(1, args.seeds + 1)]
    print(f"running {len(runs)} simulations on {args.jobs} workers ...", flush=True)
    with ThreadPoolExecutor(args.jobs) as pool:
        results = sorted(pool.map(lambda r: run_one(*r), runs),
                         key=lambda r: (int(r["n"].split(":")[0]), r["n"]))

    lines = ["# Phase 6 — UVM Regression Results", "",
             "Generated by `python3 uvm/regress.py` (Verilator 5.052 + UVM (Accellera uvm-core) + z3).", "",
             "| N:K_MAX | Test | Seeds | Passed | Jobs | Scoreboard checks |", "|---|---|---|---|---|---|"]
    by_test = defaultdict(list)
    for r in results:
        by_test[(r["n"], r["test"])].append(r)
    for (n, test), rs in sorted(by_test.items(), key=lambda kv: (tuple(map(int, kv[0][0].split(":"))), kv[0][1])):
        ok = sum(r["passed"] for r in rs)
        lines.append(f"| {n} | {test} | {len(rs)} | {ok}/{len(rs)} | {sum(r['jobs'] for r in rs)} "
                     f"| {sum(r['checks'] for r in rs)} |")
    total_ok = sum(r["passed"] for r in results)
    lines += ["", f"**{total_ok}/{len(results)} simulations passed**, "
                  f"{sum(r['jobs'] for r in results)} jobs, "
                  f"{sum(r['checks'] for r in results)} scoreboard checks.", ""]

    for n in args.config:
        hits, groups = merge_coverage([r for r in results if r["n"] == n])
        covered = sum(c for c, _ in groups.values())
        total = sum(t for _, t in groups.values())
        lines += [f"## Functional coverage, N:K_MAX = {n} (merged over all runs)", "",
                  "| Group | Covered | Bins | % |", "|---|---|---|---|"]
        for g, (c, t) in sorted(groups.items()):
            lines.append(f"| {g} | {c} | {t} | {100 * c / t:.1f} |")
        lines.append(f"| **total** | **{covered}** | **{total}** | **{100 * covered / max(total, 1):.1f}** |")
        missed = sorted(k for k, v in hits.items() if v == 0)
        lines += ["", "Not hit: " + (", ".join(f"`{k}`" for k in missed) if missed else "none"), ""]

    failed = [r for r in results if not r["passed"]]
    if failed:
        lines += ["## Failures", ""] + [f"- N={r['n']} {r['test']} seed {r['seed']}: "
                                         f"{r['errors']} UVM errors, {r['asserts']} assertion failures "
                                         f"({r['log'].relative_to(ROOT)})" for r in failed]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwrote {args.out}")
    sys.exit(0 if not failed else 1)


if __name__ == "__main__":
    main()

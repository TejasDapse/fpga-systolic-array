#!/usr/bin/env python3
"""HW/SW performance correlation (Phase 6, Day 46).

Lines up START->DONE cycles (PERF_TOTAL) and the other counters from
  analytical model   docs/results/perf_model.csv     (model/cpp/perf_table)
  SystemC CA model   docs/results/cosim_n{N}.csv     (make -C cosim, column ca_*)
  RTL simulation     docs/results/cosim_n{N}.csv     (rtl_* and pin-level cycles)
  FPGA (board)       docs/results/fpga_perf_n{N}.csv (host/mm_host --csv), when present
and writes docs/results/correlation.md plus correlation_n{N}.png.

    python3 tools/correlate.py
"""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "docs" / "results"
COUNTERS = ("total", "compute", "filldrain", "macs")


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def by_k(rows, cols):
    """K -> {counter: set of observed values}."""
    out = defaultdict(lambda: defaultdict(set))
    for r in rows:
        for name, col in cols.items():
            out[int(r["K"])][name].add(int(float(r[col])))
    return out


def err(x, ref):
    return 100.0 * abs(x - ref) / ref


def main():
    model = load(RES / "perf_model.csv")
    lines = ["# HW/SW Performance Correlation", "",
             "START→DONE cycles (PERF_TOTAL) and counters per K, from four sources. "
             "Generated by `python3 tools/correlate.py`.", ""]
    for n in (4, 8):
        pred = {int(r["K"]): {c: int(r[c]) for c in COUNTERS} for r in model if int(r["N"]) == n}
        cosim_path = RES / f"cosim_n{n}.csv"
        if not cosim_path.exists():
            lines += [f"## N = {n}", "", f"`{cosim_path.name}` missing — run `make -C cosim`.", ""]
            continue
        cosim = load(cosim_path)
        ca = by_k(cosim, {c: f"ca_{c}" for c in COUNTERS})
        rtl = by_k(cosim, {**{c: f"rtl_{c}" for c in COUNTERS}, "pins": "rtl_pin_cycles"})
        fpga_path = RES / f"fpga_perf_n{n}.csv"
        fpga = by_k(load(fpga_path), {c: c for c in COUNTERS}) if fpga_path.exists() else {}

        ks = sorted(set(ca) & set(pred))
        show = [k for k in ks if k in (1, 2, 3, 2 * n - 2, 2 * n - 1, 2 * n, 16, 32, 48, 63, 64)]
        lines += [f"## N = {n}", "",
                  "| K | analytical | SystemC CA | RTL counter | RTL pins | FPGA | max error |",
                  "|---|---|---|---|---|---|---|"]
        worst = 0.0
        mismatched = []
        for k in ks:
            p = pred[k]["total"]
            vals = {"ca": ca[k]["total"], "rtl": rtl[k]["total"], "pins": rtl[k]["pins"]}
            if k in fpga:
                vals["fpga"] = fpga[k]["total"]
            e = max(err(v, p) for s in vals.values() for v in s)
            worst = max(worst, e)
            for c in COUNTERS:                              # every counter, every source
                for src, table in (("CA", ca), ("RTL", rtl), ("FPGA", fpga)):
                    if k in table and table[k][c] != {pred[k][c]}:
                        mismatched.append(f"K={k} {src} {c}: {sorted(table[k][c])} vs {pred[k][c]}")
            if k in show:
                fmt = lambda s: "/".join(map(str, sorted(s)))
                lines.append(f"| {k} | {p} | {fmt(vals['ca'])} | {fmt(vals['rtl'])} | {fmt(vals['pins'])} "
                             f"| {fmt(vals['fpga']) if 'fpga' in vals else 'pending'} | {e:.1f} % |")
        jobs_fpga = sum(1 for _ in load(fpga_path)) if fpga_path.exists() else 0
        lines += ["", f"K values compared: {len(ks)} (all jobs of the co-sim vector file); "
                      f"worst |error| on PERF_TOTAL: **{worst:.1f} %**; "
                      f"counter mismatches (total/compute/filldrain/macs): **{len(mismatched)}**; "
                      f"FPGA jobs: {jobs_fpga or 'none yet (needs the board)'}.", ""]
        lines += [f"- {m}" for m in mismatched[:10]]
        plot(n, ks, pred, ca, rtl, fpga)
        lines += [f"![cycles vs K, N={n}](correlation_n{n}.png)", ""]

    lines += ["## Reading the numbers", "",
              "- *analytical* = `mm::predict_perf` (K + 2N); the SystemC CA model and the RTL match it "
              "exactly because the model reproduces the controller FSM and counter conditions.",
              "- *RTL pins* measures START accept → DONE from the bus pins, independent of the counters.",
              "- The FPGA column is filled by `host/mm_host --csv docs/results/fpga_perf_n{N}.csv` on the "
              "board; any difference there would point at a synthesis / timing problem, not a model gap, "
              "since the counters are cycle counts of the same RTL.",
              "- End-to-end time on the board is dominated by UART (see `host.py --bench`), not by these cycles.",
              ""]
    (RES / "correlation.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def plot(n, ks, pred, ca, rtl, fpga):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(ks, [pred[k]["total"] for k in ks], "-", lw=3, alpha=0.4, label="analytical K + 2N")
    ax.plot(ks, [min(ca[k]["total"]) for k in ks], "o", ms=3, label="SystemC CA")
    ax.plot(ks, [min(rtl[k]["pins"]) for k in ks], "x", ms=4, label="RTL (pins)")
    fk = [k for k in ks if k in fpga]
    if fk:
        ax.plot(fk, [min(fpga[k]["total"]) for k in fk], "s", ms=4, mfc="none", label="FPGA")
    ax.set_xlabel("K")
    ax.set_ylabel("START → DONE cycles")
    ax.set_title(f"N = {n}: predicted vs simulated vs measured")
    ax.legend()
    fig.tight_layout()
    fig.savefig(RES / f"correlation_n{n}.png", dpi=130)


if __name__ == "__main__":
    main()
